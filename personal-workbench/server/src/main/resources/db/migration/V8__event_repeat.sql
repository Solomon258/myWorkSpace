-- 「每周 X 做什么」这类周期日程：收录确认或手工新建时可一次生成连续 4 周。
--   需求原文（用户 2026-09-13）：「如果我收录最终进入日程的信息是每周几做什么，
--   你需要在连续 4 周的日程中都展示该记录」。
--
-- 为什么是「物化 N 条 + 分组标记」，而不是「一条记录 + 查询时展开」：
--   用户明确要求「只改其中某一次」也要能生效（2026-09-13 三选一确认）。
--   若只存一条 + 展开规则，任何一次单独修改都得引入**例外表**（记住「哪一期被单独改过」），
--   查询时再把主线与例外合并 —— 复杂度和收益完全不成比例。
--   物化之后「只改一次」天然成立（改的就是那一条），而且**查询层零改动**：
--   周视图、驾驶舱「今日日程」、冲突检测、全文检索、回收站全都自动把每一期当成一条普通日程，
--   不需要任何展开逻辑。代价是「改标题要改 4 遍」—— 但用户要的正是「每一期独立」，
--   所以这不是代价，而是预期行为。
--
-- repeat_group = 同一条重复日程的组标识，取**组内首条记录的 id**；不重复的日程为 NULL。
-- repeat_total = 该组共几期（不重复 = 1）。前端据此显示「每周 · 共 4 次」这类标注。
--   两列都不参与唯一约束与 CHECK：删掉其中一期不影响其余几期的组内关系（用户要的就是这个）。
--
-- 为什么不用重建表：这里只是**新增列**，不涉及修改 CHECK 约束、也不用去掉 NOT NULL，
--   ALTER TABLE ADD COLUMN 直接就够（V3 / V7 同理；V4/V5/V6 整表重建是因为要改 CHECK 或 NOT NULL）。
--   `repeat_total` 虽然是 NOT NULL，但**带了非空默认值**，SQLite 允许这样 ADD COLUMN。
ALTER TABLE schedule_event ADD COLUMN repeat_group INTEGER;
ALTER TABLE schedule_event ADD COLUMN repeat_total INTEGER NOT NULL DEFAULT 1;
